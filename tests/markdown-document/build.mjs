/* Bundles tests/markdown-document/harness.tsx (React + the components, from source) into
 * tests/markdown-document/dist/ for tests/a11y/markdown-document.spec.mjs (HAR-3096).
 * Not deployed, not committed.   node tests/markdown-document/build.mjs */
import { build } from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export async function buildMarkdownDocumentHarness() {
  await build({
    entryPoints: [join(here, 'harness.tsx')],
    outdir: join(here, 'dist'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    sourcemap: 'linked',
    logLevel: 'warning',
    define: { 'process.env.NODE_ENV': '"development"' },
  });
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await buildMarkdownDocumentHarness();
