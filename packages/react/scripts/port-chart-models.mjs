#!/usr/bin/env node
/* Generates packages/tokens/guide/chart-analytic.js — the analytic chart models (ChartPanels,
 * CorrelationScatter, the overlays and the stats) for the vanilla styleguide — by bundling the
 * shipped TypeScript source. The docs examples therefore draw exactly what the React components
 * draw. src/chart-analytic-port.test.mjs fails when the committed file is stale:
 *   node packages/react/scripts/port-chart-models.mjs */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const PORT_TARGET = resolve(packageRoot, '../tokens/guide/chart-analytic.js');

export async function portChartModels() {
  const result = await build({
    entryPoints: [resolve(packageRoot, 'src/chart-analytic-guide.ts')],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2020',
    legalComments: 'none',
    logLevel: 'warning',
    banner: { js: '/* GENERATED by packages/react/scripts/port-chart-models.mjs from packages/react/src (chart-panels-model,\n   correlation-scatter-model, chart-analytic-model, chart-stats, chart-theme). Do not edit; re-run the script. */' },
  });
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(PORT_TARGET, await portChartModels());
  console.log(`✓ wrote ${PORT_TARGET}`);
}
