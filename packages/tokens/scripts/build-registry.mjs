#!/usr/bin/env node
/* build-registry.mjs (DIST-2) — generate the copy-in manifest `registry/registry.json`.
 *
 * Per ADR-0017 (distribution bet, option C), the manifest is the machine-readable inventory a
 * copy-in consumer (or the `uix add` CLI, DIST-3) uses: for every CSS component it records the
 * file to copy, its cascade layer, and the exact `--uix-*` tokens it depends on. It is GENERATED
 * from the shipped CSS (never hand-maintained), so it cannot disagree with what npm publishes; a
 * drift gate (check-registry.mjs) keeps it honest.
 *
 * Token extraction reads every `var(--uix-*)` reference — including those inside `color-mix()` and
 * nested `var(--a, var(--b))` fallbacks — de-duplicated and sorted. Dependency-free. Exports
 * `generateRegistry()` (pure over the filesystem) for the drift check; running the file writes it.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, '..');
const COMPONENTS_DIR = join(PKG_ROOT, 'styles', 'components');
const OUT = join(PKG_ROOT, 'registry', 'registry.json');

export const SCHEMA_VERSION = '1.0';

/** All `--uix-*` custom properties referenced via var() in a CSS string, unique + sorted. */
export function extractTokens(css) {
  const names = new Set();
  const re = /var\(\s*(--uix-[a-z0-9-]+)/gi;
  let m;
  while ((m = re.exec(css)) !== null) names.add(m[1]);
  return [...names].sort();
}

/** The cascade layer a component declares (first `@layer <name>`), or null. */
export function extractLayer(css) {
  const m = css.match(/@layer\s+([a-z0-9._-]+)/i);
  return m ? m[1] : null;
}

/** Build the registry object from the on-disk component CSS. Pure w.r.t. the filesystem. */
export function generateRegistry() {
  const files = readdirSync(COMPONENTS_DIR)
    .filter((f) => f.endsWith('.css'))
    .sort();
  const components = files.map((f) => {
    const css = readFileSync(join(COMPONENTS_DIR, f), 'utf8');
    return {
      name: f.replace(/\.css$/, ''),
      file: `styles/components/${f}`,
      layer: extractLayer(css),
      tokens: extractTokens(css),
    };
  });
  return {
    $comment:
      'GENERATED by packages/tokens/scripts/build-registry.mjs from styles/components/*.css. Do not edit by hand — run `npm run build:registry`. Drift-gated by check-registry.mjs (test:registry).',
    schemaVersion: SCHEMA_VERSION,
    count: components.length,
    components,
  };
}

export function serialize(reg) {
  return JSON.stringify(reg, null, 2) + '\n';
}

function main() {
  const reg = generateRegistry();
  if (reg.count !== 67) {
    console.error(`✗ registry: expected 67 components, found ${reg.count} — did a component CSS file get added/removed?`);
    process.exit(1);
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, serialize(reg));
  console.log(`✓ registry/registry.json — ${reg.count} components`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
