#!/usr/bin/env node
/* build-docs-index.mjs — derive docs/data/components.json from the api-extractor report.
 *
 * The docs site (DOCS-2) renders per-component pages. The props table for each page is not
 * hand-authored — it is the SINGLE SOURCE OF TRUTH extracted from
 * packages/react/etc/uix-react.api.md (the api-extractor lock, gated by `test:api`). This keeps
 * the docs props in lockstep with the shipped types: regenerate after any api.md change.
 *
 * Pinned to the api-extractor block format:
 *   - Exported components:  `export function Name(` and `export const Name:`
 *   - Props interfaces:     `export interface NameProps extends BASE {` … `}` with one
 *                           `    name?: type;` (or `name: type;`) prop per line and
 *                           `// (undocumented)` comment lines interleaved.
 * A component `Name` is paired with the interface `NameProps` (the library's naming convention).
 * Components with no `NameProps` interface (inline-typed sub-parts) carry an empty props array.
 *
 * Pure `parseApiMd(text)` is exported for the unit test; running the file writes the JSON.
 * Node built-ins only. */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const API_MD = resolve(__dirname, '../../react/etc/uix-react.api.md');
const OUT = resolve(__dirname, '../docs/data/components.json');

/** URL-safe slug, identical rule to docs.js slugify (kept in sync intentionally). */
export const slugify = (name) =>
  String(name)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

/** Parse a single `export interface NameProps extends BASE {` … `}` block body into props. */
function parseInterfaceBody(lines, startIdx) {
  const props = [];
  for (let i = startIdx; i < lines.length; i++) {
    const line = lines[i].trim();
    if (line === '}') return { props, endIdx: i };
    if (line === '' || line.startsWith('//')) continue;
    // one prop per line: `name?: type;`  or  `readonly name: type;`
    const m = line.match(/^(?:readonly\s+)?([A-Za-z_$][\w$]*)(\?)?:\s*(.+);$/);
    if (m) {
      props.push({ name: m[1], type: m[3].trim(), optional: Boolean(m[2]) });
    }
    // index signatures / method-ish lines are ignored (not surfaced in the docs table)
  }
  return { props, endIdx: lines.length };
}

/** Parse the api-extractor report text into { components: [...] }. Pure — no file IO. */
export function parseApiMd(md) {
  const lines = md.split(/\r?\n/);

  // 1. Collect every `NameProps` interface with its extends clause + props.
  const interfaces = new Map();
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/^export interface ([A-Za-z0-9_]+Props)(?:<[^>]*>)?(?:\s+extends\s+(.+?))?\s*\{$/);
    if (m) {
      const { props, endIdx } = parseInterfaceBody(lines, i + 1);
      interfaces.set(m[1], { extends: m[2] ? m[2].trim() : null, props });
      i = endIdx;
    }
  }

  // 2. Collect exported component names in source order. A *component* is an export that returns
  //    JSX (`react.JSX.Element`) or is a `ForwardRefExoticComponent` — this excludes exported
  //    utilities (cx, applyFilters, clampWidth, highlightSegments) that share `export function`.
  const names = [];
  const seen = new Set();
  for (const line of lines) {
    const m = line.match(/^export (?:function|const) ([A-Za-z0-9_]+)\b/);
    if (m && !seen.has(m[1]) && /JSX\.Element|ForwardRefExoticComponent/.test(line)) {
      seen.add(m[1]);
      names.push(m[1]);
    }
  }

  // 3. Pair each component with its NameProps interface (empty props if none).
  const components = names.map((name) => {
    const iface = interfaces.get(`${name}Props`);
    return {
      name,
      slug: slugify(name),
      extends: iface ? iface.extends : null,
      props: iface ? iface.props : [],
    };
  });

  return { components };
}

function main() {
  const md = readFileSync(API_MD, 'utf8');
  const data = parseApiMd(md);
  const json = {
    $comment:
      'GENERATED by packages/tokens/scripts/build-docs-index.mjs from packages/react/etc/uix-react.api.md. Do not edit by hand — run `npm run docs:build`.',
    generatedFrom: 'packages/react/etc/uix-react.api.md',
    count: data.components.length,
    components: data.components,
  };
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, JSON.stringify(json, null, 2) + '\n');
  console.log(`✓ docs/data/components.json — ${data.components.length} components`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
